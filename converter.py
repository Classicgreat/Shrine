def parse_ansi(line):
    """Возвращает список (символ, цвет_текста, цвет_фона) для каждого символа в строке"""
    result = []
    i = 0
    fg = 0  # 0 - сброс
    bg = 0
    while i < len(line):
        if line[i] == '\033' and i+1 < len(line) and line[i+1] == '[':
            i += 2
            params = []
            num = 0
            while i < len(line) and line[i] != 'm':
                if line[i].isdigit():
                    num = num*10 + int(line[i])
                elif line[i] == ';':
                    params.append(num)
                    num = 0
                i += 1
            if i < len(line) and line[i] == 'm':
                params.append(num)
                i += 1
                # Применяем параметры
                if not params or params[0] == 0:
                    fg = 0
                    bg = 0
                else:
                    for p in params:
                        if 30 <= p <= 37:
                            fg = p
                        elif 40 <= p <= 47:
                            bg = p
                        elif p == 0:
                            fg = 0
                            bg = 0
                        # другие (жирный) игнорируем
                continue
        else:
            # Обычный символ (включая пробел)
            result.append((line[i], fg, bg))
            i += 1
    return result

